#!/usr/bin/env node
// Generates upload-config.php into the build output for the FTP deploy step.
//
// Required env:
//   SUPABASE_JWT_SECRET   Supabase project JWT secret (HS256, NOT the anon key)
//   ADMIN_EMAILS          comma-separated list of admin emails (lowercased)
//   UPLOADS_URL           public URL prefix, e.g. https://theciovision.com/uploads
// Optional env:
//   MIGRATION_TOKEN       leave unset/empty in normal operation; set only during the
//                         one-time bulk migration run, then unset

import { writeFileSync } from 'node:fs';
import { join } from 'node:path';

const outDir = process.argv[2] || 'build';

const jwtSecret = process.env.SUPABASE_JWT_SECRET || '';
const adminEmails = (process.env.ADMIN_EMAILS || '')
  .split(',')
  .map((s) => s.trim().toLowerCase())
  .filter(Boolean);
const uploadsUrl = process.env.UPLOADS_URL || '';
const migrationToken = process.env.MIGRATION_TOKEN || '';

if (!jwtSecret) throw new Error('SUPABASE_JWT_SECRET is required');
if (adminEmails.length === 0) throw new Error('ADMIN_EMAILS is required (comma-separated)');
if (!uploadsUrl) throw new Error('UPLOADS_URL is required');

const phpString = (s) =>
  "'" + String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'") + "'";

const emailLines = adminEmails.map((e) => `        ${phpString(e)},`).join('\n');

const php = `<?php
// Generated by scripts/generate-upload-config.mjs during CI.
// Do NOT edit this file on the Hostinger server — every deploy overwrites it.

return [
    'jwt_secret' => ${phpString(jwtSecret)},
    'admin_emails' => [
${emailLines}
    ],
    'uploads_path' => __DIR__ . '/uploads',
    'uploads_url' => ${phpString(uploadsUrl)},
    'migration_token' => ${phpString(migrationToken)},
];
`;

const outPath = join(outDir, 'upload-config.php');
writeFileSync(outPath, php, 'utf8');
console.log(`Wrote ${outPath} (${adminEmails.length} admin email${adminEmails.length === 1 ? '' : 's'})`);
